import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { loadRiskReapprovalUpgrade } from './lib/risk-reapproval-upgrade.mjs'
import { tableDefinitionHash } from './lib/inplace-foundation-upgrade.mjs'

const root = new URL('../', import.meta.url)
const plan = await loadRiskReapprovalUpgrade(root)
assert.equal(plan.prior.steps.length, 267)
assert.equal(plan.steps.length, 278)
assert.equal(plan.added.length, 4)
const tables = ['bridge_installation_request_limits', 'bridge_installation_authorizations', 'bridge_installation_requests', 'bridge_refresh_sessions']
const value = { steps: plan.steps.map(({ id, checksum }) => ({ id, checksum })), tables: tables.map(table => {
  const ddl = plan.definitions[table]
  assert.equal(typeof ddl, 'string', 'bridge_installation_reference_definition_missing')
  const schemaSha256 = tableDefinitionHash(ddl)
  assert.equal(schemaSha256, plan.finalTableHashes[table])
  return { table, schemaSha256 }
}) }
const rendered = '// Generated by scripts/generate-bridge-installation-schema-readiness.mjs; do not edit.\nexport const bridgeInstallationSchema = '
  + JSON.stringify(value, null, 2) + ' as const\n'
const destination = new URL('server/src/modules/bridge/infrastructure/bridge-installation-schema.ts', root)
if (process.argv[2] === '--check') assert.equal(await readFile(destination, 'utf8'), rendered, 'bridge_installation_schema_generation_drift')
else { assert.equal(process.argv.length, 2); await writeFile(destination, rendered) }
console.log(JSON.stringify({ steps: value.steps.length, requiredTables: value.tables.length }))
