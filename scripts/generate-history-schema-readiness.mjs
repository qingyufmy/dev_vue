import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { loadHistoryRuntimeUpgrade } from './lib/history-runtime-upgrade.mjs'
const root = new URL('../', import.meta.url)
const reference = JSON.parse(await readFile(new URL('docs/architecture/history-runtime-reference-20260909.json', root), 'utf8'))
const plan = await loadHistoryRuntimeUpgrade(root, reference)
const value = { steps: plan.steps.map(({ id, checksum }) => ({ id, checksum })),
  tables: Object.entries(plan.finalTableHashes).map(([table, schemaSha256]) => ({ table, schemaSha256 })) }
const rendered = '// Generated by scripts/generate-history-schema-readiness.mjs; do not edit.\n'
  + 'export const historyRuntimeSchema = ' + JSON.stringify(value, null, 2) + ' as const\n'
const destination = new URL('server/src/modules/trade-history/infrastructure/history-runtime-schema.ts', root)
if (process.argv[2] === '--check') assert.equal(await readFile(destination, 'utf8'), rendered)
else { assert.equal(process.argv.length, 2); await writeFile(destination, rendered) }
console.log('History runtime schema requirements match the 188-step upgrade plan')
