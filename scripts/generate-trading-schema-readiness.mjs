import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { loadTradingContextChanges } from './lib/inplace-trading-context-changes.mjs'
import { hash } from './lib/v4-backfill-contract.mjs'
import { loadRiskReapprovalUpgrade } from './lib/risk-reapproval-upgrade.mjs'
import { tableDefinitionHash } from './lib/inplace-foundation-upgrade.mjs'

const root = new URL('../', import.meta.url)
const destination = new URL('server/src/modules/trading/infrastructure/inplace-account-schema.ts', root)
// Consumed account/context/read projection schema. Other domains need their own checks.
const tables = ['database_upgrade_steps_v4', 'users', 'trading_accounts', 'user_trading_account_settings',
  'trading_account_ownerships', 'trading_account_ownership_intervals', 'terminal_profiles', 'terminal_account_bindings',
  'bridge_connection_sessions', 'bridge_connection_capacity_grants', 'bridge_refresh_sessions',
  'observer_sources', 'observer_channels', 'observer_channel_accesses', 'trading_contexts',
  'account_runtime_snapshots', 'market_quotes', 'market_candles', 'open_position_snapshots', 'pending_order_snapshots',
  'trading_projection_revisions', 'trading_projection_provenance_v4', 'trading_context_changes_v4']

export async function renderTradingSchemaReadiness() {
  const plan = await loadTradingContextChanges(root)
  const proof = JSON.parse(await readFile(new URL('docs/architecture/current-context-changes-proof-20260908.json', root), 'utf8'))
  const { proofHash, ...body } = proof
  assert.equal(hash(body), proofHash)
  assert.equal(proof.registryHash, hash(plan.steps.map(({ id, checksum }) => ({ id, checksum }))))
  const installation = await loadRiskReapprovalUpgrade(root)
  assert.equal(installation.steps.length, 278)
  assert.deepEqual(installation.steps.slice(0, plan.steps.length).map(({ id, checksum }) => ({ id, checksum })), plan.steps.map(({ id, checksum }) => ({ id, checksum })))
  const refreshHash = tableDefinitionHash(installation.definitions.bridge_refresh_sessions)
  assert.equal(refreshHash, installation.finalTableHashes.bridge_refresh_sessions)
  const expected = tables.map(table => {
    const schemaSha256 = table === 'bridge_refresh_sessions' ? refreshHash : table === 'trading_context_changes_v4' ? proof.definition.schemaHash
      : proof.priorSnapshot.find(row => row.name === table)?.schemaSha256
    assert.match(schemaSha256 ?? '', /^[a-f0-9]{64}$/)
    return { table, schemaSha256 }
  })
  const contract = { profile: 'inplace-account-278/v1',
    steps: installation.steps.map(({ id, checksum }) => ({ id, checksum })), tables: expected }
  return '// Generated by scripts/generate-trading-schema-readiness.mjs; do not edit.\n'
    + '// Contains schema/checksum requirements only, never database identity or row data.\n'
    + 'export const inplaceAccountSchema = ' + JSON.stringify(contract, null, 2) + ' as const\n'
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rendered = await renderTradingSchemaReadiness()
  if (process.argv[2] === '--check') assert.equal(await readFile(destination, 'utf8'), rendered, 'trading_schema_generation_drift')
  else { assert.equal(process.argv.length, 2); await writeFile(destination, rendered) }
  console.log('Trading schema requirements match 278 registered steps and 23 consumed tables')
}
