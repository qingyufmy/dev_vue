const FIXED_SET_PATTERNS = fixedSetPatterns()

function inspectSet(tokens) {
  if (!FIXED_SET_PATTERNS.some(pattern => matches(tokens, pattern))) fail('backup_sql_set_forbidden')
}

function inspectCommit(tokens) {
  if (tokens.length !== 1 || word(tokens[0]) !== 'commit') fail('backup_sql_statement_forbidden')
}

function inspectReferences(tokens, bodyStart, bodyEnd, expected) {
  for (let index = bodyStart; index < bodyEnd; index += 1) {
    if (word(tokens[index]) !== 'references') continue
    const reference = tokens[index + 1]
    if (!isIdentifierToken(reference)) fail('backup_sql_reference_invalid')
    const name = identifierValue(reference)
    if (!expected.has(name)) fail('backup_sql_reference_invalid')
    if (tokens[index + 2]?.kind === 'punct' && tokens[index + 2].value === '.') fail('backup_sql_cross_schema_identifier')
  }
}

function inspectFunctionCalls(tokens, bodyStart, bodyEnd, allowedParenOpenings = new Set(), indexPrefixOpenings = new Set()) {
  const validIndexPrefix = index => {
    const opening = tokens[index + 1]
    const value = tokens[index + 2]
    return opening?.kind === 'punct' && opening.value === '('
      && value?.kind === 'number' && /^[0-9]+$/u.test(value.value)
      && tokens[index + 3]?.kind === 'punct' && tokens[index + 3].value === ')'
  }
  for (let index = bodyStart; index + 1 < bodyEnd; index += 1) {
    const token = tokens[index]
    if (tokens[index + 1].kind !== 'punct' || tokens[index + 1].value !== '(') continue
    if (token.kind !== 'word' && token.kind !== 'identifier') continue
    const openingIndex = index + 1
    const grammarOpening = allowedParenOpenings.has(openingIndex)
    const indexPrefix = indexPrefixOpenings.has(openingIndex) && validIndexPrefix(index)
    if (token.kind === 'word') {
      const name = token.value.toLowerCase()
      // MySQL renders NOT REGEXP_LIKE as NOT(regexp_like(...)) in SHOW CREATE.
      const unaryNot = name === 'not' && (isPunctuation(tokens[index - 1], '(')
        || ['and', 'or', 'xor'].includes(word(tokens[index - 1])))
      if (grammarOpening || unaryNot || BUILTIN_CALLS.has(name)) continue
      if (indexPrefix) continue
      fail('backup_sql_function_forbidden')
    }
    if (token.kind === 'identifier') {
      if (grammarOpening || indexPrefix) continue
    }
    fail('backup_sql_function_forbidden')
  }
}

function inspectEngine(options) {
  let found = false
  for (let index = 0; index < options.length; index += 1) {
    if (word(options[index]) !== 'engine') continue
    found = true
    if (options[index + 1]?.value !== '=' || !isIdentifierToken(options[index + 2])) fail('backup_sql_engine_invalid')
    const value = identifierValue(options[index + 2])
    if (value.toLowerCase() !== 'innodb') fail('backup_sql_engine_forbidden')
  }
  if (!found) fail('backup_sql_engine_invalid')
}

function inspectDdlOptions(tokens, options) {
  for (let index = 0; index < tokens.length; index += 1) {
    const current = word(tokens[index])
    const next = word(tokens[index + 1])
    if ((current === 'data' && next === 'directory') || (current === 'index' && next === 'directory')) {
      fail('backup_sql_ddl_option_forbidden')
    }
    if (current === 'tablespace' || current === 'encryption') fail('backup_sql_ddl_option_forbidden')
    if (current === 'select') fail('backup_sql_create_as_forbidden')
    if (current === 'like') fail('backup_sql_create_like_forbidden')
  }
  let index = 0
  const optionWords = new Set(['auto_increment', 'character', 'charset', 'collate', 'comment', 'default',
    'engine', 'key_block_size', 'row_format', 'stats_auto_recalc', 'stats_persistent', 'stats_sample_pages'])
  const valueWords = new Set(['compact', 'default', 'dynamic', 'innodb', 'redundant', 'utf8mb4', 'utf8mb4_0900_ai_ci',
    'utf8mb4_general_ci', 'utf8mb4_unicode_ci'])
  const consumeAssignment = (name, allowed = () => true) => {
    if (options[index]?.value !== '=') fail('backup_sql_ddl_option_invalid')
    const value = options[index + 1]
    if (!value || !['word', 'identifier', 'number', 'string'].includes(value.kind) || !allowed(value)) {
      fail('backup_sql_ddl_option_invalid')
    }
    index += 2
  }
  while (index < options.length) {
    const current = word(options[index])
    if (current === 'default' && word(options[index + 1]) === 'character' && word(options[index + 2]) === 'set') {
      index += 3
      consumeAssignment('character_set', value => value.kind === 'word' && valueWords.has(value.value.toLowerCase()))
      continue
    }
    if (current === 'default' && word(options[index + 1]) === 'charset') {
      index += 2
      consumeAssignment('charset', value => value.kind === 'word' && valueWords.has(value.value.toLowerCase()))
      continue
    }
    if (current === 'character' && word(options[index + 1]) === 'set') {
      index += 2
      consumeAssignment('character_set', value => value.kind === 'word' && valueWords.has(value.value.toLowerCase()))
      continue
    }
    if (current === 'charset' || current === 'collate') {
      index += 1
      consumeAssignment(current, value => value.kind === 'word' && valueWords.has(value.value.toLowerCase()))
      continue
    }
    if (current === 'engine') {
      index += 1
      if (options[index]?.value !== '=' || !isIdentifierToken(options[index + 1])) fail('backup_sql_engine_invalid')
      if (identifierValue(options[index + 1]).toLowerCase() !== 'innodb') fail('backup_sql_engine_forbidden')
      index += 2
      continue
    }
    if (current === 'comment') {
      index += 1
      consumeAssignment('comment', value => value.kind === 'string')
      continue
    }
    if (current === 'row_format') {
      index += 1
      consumeAssignment('row_format', value => value.kind === 'word' && ['compact', 'dynamic', 'redundant', 'compressed'].includes(value.value.toLowerCase()))
      continue
    }
    if (current === 'auto_increment' || current === 'key_block_size' || current === 'stats_sample_pages') {
      index += 1
      consumeAssignment(current, value => value.kind === 'number' && /^[0-9]+$/u.test(value.value))
      continue
    }
    if (current === 'stats_auto_recalc' || current === 'stats_persistent') {
      index += 1
      consumeAssignment(current, value => (value.kind === 'number' && /^[01]$/u.test(value.value))
        || (value.kind === 'word' && value.value.toLowerCase() === 'default'))
      continue
    }
    if (!optionWords.has(current)) fail('backup_sql_ddl_option_forbidden')
    fail('backup_sql_ddl_option_invalid')
  }
  inspectEngine(options)
}

const TABLE_CONSTRAINT_WORDS = new Set([
  'check', 'constraint', 'foreign', 'fulltext', 'index', 'key', 'primary', 'spatial', 'unique',
])
const INDEX_DEFINITION_WORDS = new Set(['fulltext', 'index', 'key', 'primary', 'spatial', 'unique'])
const TYPE_PAREN_WORDS = new Set([
  'bigint', 'binary', 'bit', 'blob', 'bool', 'boolean', 'char', 'character',
  'datetime', 'decimal', 'dec', 'double', 'enum', 'fixed', 'float', 'geometry', 'geometrycollection',
  'int', 'integer', 'json', 'linestring', 'longblob', 'longtext', 'mediumblob',
  'mediumint', 'mediumtext', 'multilinestring', 'multipoint', 'multipolygon',
  'numeric', 'point', 'polygon', 'real', 'set', 'smallint', 'text', 'time',
  'timestamp', 'tinyblob', 'tinyint', 'tinytext', 'varbinary', 'varchar', 'year',
])
const EXPRESSION_END_WORDS = new Set(['false', 'null', 'true'])
const EXPRESSION_NON_END_WORDS = new Set([
  'and', 'as', 'between', 'case', 'else', 'end', 'in', 'is', 'like', 'not', 'or', 'regexp',
  'then', 'when', 'xor',
])

function isTableConstraintStart(token) {
  return token?.kind === 'word' && TABLE_CONSTRAINT_WORDS.has(token.value.toLowerCase())
}

function findMatchingParen(tokens, opening, end) {
  let depth = 0
  for (let index = opening; index < end; index += 1) {
    const token = tokens[index]
    if (isPunctuation(token, '(')) depth += 1
    else if (isPunctuation(token, ')')) {
      depth -= 1
      if (depth < 0) return -1
      if (depth === 0) return index
    }
  }
  return -1
}

function splitCreateDefinitions(tokens, start, end) {
  const definitions = []
  let itemStart = start
  let depth = 0
  for (let index = start; index < end; index += 1) {
    const token = tokens[index]
    if (isPunctuation(token, '(')) {
      depth += 1
      continue
    }
    if (isPunctuation(token, ')')) {
      depth -= 1
      if (depth < 0) fail('backup_sql_create_shape_invalid')
      continue
    }
    if (isPunctuation(token, ',') && depth === 0) {
      if (itemStart === index) fail('backup_sql_create_shape_invalid')
      definitions.push({ start: itemStart, end: index })
      itemStart = index + 1
    }
  }
  if (depth !== 0 || itemStart >= end) fail('backup_sql_create_shape_invalid')
  definitions.push({ start: itemStart, end })
  return definitions
}

function expressionCanEndBefore(tokens, index) {
  const token = tokens[index]
  if (!token) return false
  if (token.kind === 'identifier' || token.kind === 'number' || token.kind === 'string') return true
  if (token.kind === 'punct' && token.value === ')') return true
  if (token.kind !== 'word') return false
  const name = token.value.toLowerCase()
  return EXPRESSION_END_WORDS.has(name) || !EXPRESSION_NON_END_WORDS.has(name)
}

function collectExpressionGrammarOpenings(tokens, start, end, allowedParenOpenings) {
  let caseDepth = 0
  let depth = 0
  for (let index = start; index < end; index += 1) {
    const token = tokens[index]
    const current = word(token)
    if (current === 'case') caseDepth += 1
    if (current === 'end' && caseDepth > 0) caseDepth -= 1
    if (token.kind !== 'punct') continue
    if (token.value === '(') {
      const previousWord = word(tokens[index - 1])
      const beforeKeyword = index - 2
      if (previousWord === 'when' && caseDepth > 0
        && (word(tokens[beforeKeyword]) === 'case' || expressionCanEndBefore(tokens, beforeKeyword))) {
        allowedParenOpenings.add(index)
      }
      if ((previousWord === 'then' || previousWord === 'else') && caseDepth > 0
        && expressionCanEndBefore(tokens, beforeKeyword)) {
        allowedParenOpenings.add(index)
      }
      if (previousWord === 'in' || previousWord === 'and' || previousWord === 'or') {
        let leftIndex = index - 2
        if (previousWord === 'in' && word(tokens[leftIndex]) === 'not') leftIndex -= 1
        if (expressionCanEndBefore(tokens, leftIndex)) allowedParenOpenings.add(index)
      }
      depth += 1
    } else if (token.value === ')') {
      depth -= 1
      if (depth < 0) fail('backup_sql_create_shape_invalid')
    }
  }
  if (depth !== 0) fail('backup_sql_create_shape_invalid')
}

function collectIndexPrefixOpenings(tokens, opening, end, indexPrefixOpenings) {
  const close = findMatchingParen(tokens, opening, end)
  if (close < 0) fail('backup_sql_create_shape_invalid')
  let depth = 0
  for (let index = opening + 1; index < close; index += 1) {
    const token = tokens[index]
    if (isPunctuation(token, '(')) {
      if (depth === 0 && isIdentifierToken(tokens[index - 1])
        && tokens[index + 1]?.kind === 'number'
        && /^[0-9]+$/u.test(tokens[index + 1].value)
        && isPunctuation(tokens[index + 2], ')')) {
        indexPrefixOpenings.add(index)
      }
      depth += 1
    } else if (isPunctuation(token, ')')) {
      depth -= 1
      if (depth < 0) fail('backup_sql_create_shape_invalid')
    }
  }
  if (depth !== 0) fail('backup_sql_create_shape_invalid')
}

function collectConstraintOpenings(tokens, start, end, allowedParenOpenings, indexPrefixOpenings) {
  const indexListOpenings = []
  for (let index = start; index < end; index += 1) {
    if (!isPunctuation(tokens[index], '(')) continue
    const previous = tokens[index - 1]
    const previousWord = word(previous)
    const beforePreviousWord = word(tokens[index - 2])
    const indexOpening = INDEX_DEFINITION_WORDS.has(previousWord)
      || (isIdentifierToken(previous) && INDEX_DEFINITION_WORDS.has(beforePreviousWord))
    const referencesOpening = isIdentifierToken(previous) && beforePreviousWord === 'references'
    if (indexOpening || referencesOpening || previousWord === 'check') {
      allowedParenOpenings.add(index)
      if (indexOpening) indexListOpenings.push(index)
    }
  }
  for (const opening of indexListOpenings) collectIndexPrefixOpenings(tokens, opening, end, indexPrefixOpenings)
  collectExpressionGrammarOpenings(tokens, start, end, allowedParenOpenings)
}

function collectColumnOpenings(tokens, start, end, generatedAsIndex, allowedParenOpenings) {
  const type = word(tokens[start + 1])
  if (TYPE_PAREN_WORDS.has(type) && isPunctuation(tokens[start + 2], '(')) {
    allowedParenOpenings.add(start + 2)
  } else if ((type === 'national' || type === 'character') && TYPE_PAREN_WORDS.has(word(tokens[start + 2]))
    && isPunctuation(tokens[start + 3], '(')) {
    allowedParenOpenings.add(start + 3)
  }

  let depth = 0
  for (let index = start + 1; index < end; index += 1) {
    const token = tokens[index]
    if (isPunctuation(token, '(')) {
      if (depth === 0 && word(tokens[index - 1]) === 'default') allowedParenOpenings.add(index)
      if (index === generatedAsIndex + 1) allowedParenOpenings.add(index)
      depth += 1
    } else if (isPunctuation(token, ')')) {
      depth -= 1
      if (depth < 0) fail('backup_sql_create_shape_invalid')
    }
  }
  if (depth !== 0) fail('backup_sql_create_shape_invalid')
  collectExpressionGrammarOpenings(tokens, start + 1, end, allowedParenOpenings)
}

function inspectColumnDefinition(tokens, start, end, allowedParenOpenings) {
  if (!isIdentifierToken(tokens[start]) || end <= start + 1) fail('backup_sql_create_columns_invalid')
  const name = identifierValue(tokens[start])
  const topLevelWords = []
  let depth = 0
  for (let index = start + 1; index < end; index += 1) {
    const token = tokens[index]
    if (isPunctuation(token, '(')) {
      depth += 1
      continue
    }
    if (isPunctuation(token, ')')) {
      depth -= 1
      if (depth < 0) fail('backup_sql_create_shape_invalid')
      continue
    }
    if (depth === 0 && token.kind === 'word') topLevelWords.push(index)
  }
  if (depth !== 0) fail('backup_sql_create_shape_invalid')

  const asIndexes = topLevelWords.filter(index => word(tokens[index]) === 'as')
  const generatedIndexes = topLevelWords.filter(index => word(tokens[index]) === 'generated')
  const alwaysIndexes = topLevelWords.filter(index => word(tokens[index]) === 'always')
  if (asIndexes.length > 1 || generatedIndexes.length > 1 || alwaysIndexes.length > 1) {
    fail('backup_sql_create_shape_invalid')
  }

  let generated = false
  let generatedAsIndex = -1
  if (asIndexes.length > 0) {
    generatedAsIndex = asIndexes[0]
    if (generatedAsIndex <= start + 1 || (generatedIndexes.length > 0
      && (generatedIndexes[0] + 2 !== generatedAsIndex || word(tokens[generatedIndexes[0] + 1]) !== 'always'))
      || (generatedIndexes.length === 0 && alwaysIndexes.length > 0)) {
      fail('backup_sql_create_shape_invalid')
    }
    const expressionOpen = generatedAsIndex + 1
    if (tokens[expressionOpen]?.kind !== 'punct' || tokens[expressionOpen].value !== '(') {
      fail('backup_sql_create_shape_invalid')
    }
    const expressionClose = findMatchingParen(tokens, expressionOpen, end)
    if (expressionClose < 0 || expressionClose === expressionOpen + 1) fail('backup_sql_create_shape_invalid')
    if (topLevelWords.some(index => word(tokens[index]) === 'default')) fail('backup_sql_create_shape_invalid')
    generated = true
  } else if (generatedIndexes.length > 0 || alwaysIndexes.length > 0) {
    fail('backup_sql_create_shape_invalid')
  }

  collectColumnOpenings(tokens, start, end, generatedAsIndex, allowedParenOpenings)
  return { name, generated }
}

function inspectCreateDefinitions(tokens, bodyStart, bodyEnd, table) {
  const definitions = splitCreateDefinitions(tokens, bodyStart, bodyEnd)
  const columnNames = []
  const generatedColumns = new Set()
  const allowedParenOpenings = new Set()
  const indexPrefixOpenings = new Set()
  for (const definition of definitions) {
    if (isTableConstraintStart(tokens[definition.start])) {
      collectConstraintOpenings(tokens, definition.start, definition.end, allowedParenOpenings, indexPrefixOpenings)
      continue
    }
    const column = inspectColumnDefinition(tokens, definition.start, definition.end, allowedParenOpenings)
    columnNames.push(column.name)
    if (column.generated) generatedColumns.add(column.name)
  }
  if (columnNames.length !== table.columns.length
    || columnNames.some((name, index) => name !== table.columns[index])) {
    fail('backup_sql_create_columns_invalid')
  }
  return { generatedColumns, allowedParenOpenings, indexPrefixOpenings }
}

function inspectCreate(tokens, expected, tableMap) {
  if (word(tokens[0]) !== 'create' || word(tokens[1]) !== 'table') fail('backup_sql_object_forbidden')
  if (word(tokens[2]) === 'temporary' || word(tokens[2]) === 'view' || word(tokens[2]) === 'database') {
    fail('backup_sql_object_forbidden')
  }
  const tableName = identifierValue(tokens[2])
  if (tokens[3]?.kind === 'punct' && tokens[3].value === '.') fail('backup_sql_cross_schema_identifier')
  const table = tableMap.get(tableName)
  if (!table) fail('backup_sql_unknown_table')
  if (table.created) fail('backup_sql_duplicate_table')
  if (tokens[3]?.value !== '(') fail('backup_sql_create_shape_invalid')
  let depth = 0
  let close = -1
  for (let index = 3; index < tokens.length; index += 1) {
    if (tokens[index].kind === 'punct' && tokens[index].value === '(') depth += 1
    else if (tokens[index].kind === 'punct' && tokens[index].value === ')') {
      depth -= 1
      if (depth < 0) fail('backup_sql_create_shape_invalid')
      if (depth === 0) {
        close = index
        break
      }
    }
  }
  if (close < 0 || close === 4) fail('backup_sql_create_shape_invalid')
  const bodyEnd = close
  const options = tokens.slice(close + 1)
  const ddl = inspectCreateDefinitions(tokens, 4, bodyEnd, table)
  inspectReferences(tokens, 3, bodyEnd, expected)
  inspectFunctionCalls(tokens, 3, bodyEnd, ddl.allowedParenOpenings, ddl.indexPrefixOpenings)
  inspectDdlOptions(tokens, options)
  table.generatedColumns = ddl.generatedColumns
  table.created = true
}

const NUMERIC_LITERAL = /^[+-]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)(?:[eE][+-]?[0-9]+)?$/u
const HEX_LITERAL = /^0x[0-9A-Fa-f]+$/u

function inspectLiteral(tokens, start) {
  const token = tokens[start]
  if (!token) fail('backup_sql_insert_values_invalid')
  if (token.kind === 'string') return start + 1
  if (token.kind === 'word' && token.value.toLowerCase() === 'null') return start + 1
  if (token.kind === 'number') {
    if (!HEX_LITERAL.test(token.value) && !NUMERIC_LITERAL.test(token.value)) fail('backup_sql_insert_values_invalid')
    return start + 1
  }
  if (token.kind === 'punct' && (token.value === '+' || token.value === '-') && tokens[start + 1]?.kind === 'number') {
    const combined = `${token.value}${tokens[start + 1].value}`
    if (!NUMERIC_LITERAL.test(combined)) fail('backup_sql_insert_values_invalid')
    return start + 2
  }
  if (token.kind === 'word' && CONTROLLED_PREFIXES.has(token.value.toLowerCase()) && tokens[start + 1]?.kind === 'string') {
    const prefix = token.value.toLowerCase()
    const value = stringValue(tokens[start + 1])
    if (prefix === 'x' && (!/^[0-9A-Fa-f]*$/u.test(value) || value.length % 2 !== 0)) fail('backup_sql_insert_values_invalid')
    if (prefix === 'b' && !/^[01]*$/u.test(value)) fail('backup_sql_insert_values_invalid')
    return start + 2
  }
  fail('backup_sql_insert_values_invalid')
}

function inspectInsert(tokens, tableMap) {
  if (word(tokens[0]) !== 'insert' || word(tokens[1]) !== 'into') fail('backup_sql_insert_shape_invalid')
  const tableName = identifierValue(tokens[2])
  if (tokens[3]?.kind === 'punct' && tokens[3].value === '.') fail('backup_sql_cross_schema_identifier')
  const table = tableMap.get(tableName)
  if (!table) fail('backup_sql_unknown_table')
  if (!table.created) fail('backup_sql_insert_before_create')
  if (tokens[3]?.value !== '(') fail('backup_sql_insert_columns_invalid')
  const columns = []
  let index = 4
  while (index < tokens.length && tokens[index].value !== ')') {
    if (!isIdentifierToken(tokens[index])) fail('backup_sql_insert_columns_invalid')
    columns.push(identifierValue(tokens[index]))
    index += 1
    if (tokens[index]?.value === ',') index += 1
    else if (tokens[index]?.value !== ')') fail('backup_sql_insert_columns_invalid')
  }
  let expectedIndex = 0
  for (const name of columns) {
    if (table.generatedColumns.has(name)) fail('backup_sql_insert_columns_invalid')
    while (expectedIndex < table.columns.length && table.generatedColumns.has(table.columns[expectedIndex])
      && table.columns[expectedIndex] !== name) expectedIndex += 1
    if (name !== table.columns[expectedIndex]) fail('backup_sql_insert_columns_invalid')
    expectedIndex += 1
  }
  while (expectedIndex < table.columns.length && table.generatedColumns.has(table.columns[expectedIndex])) expectedIndex += 1
  if (tokens[index]?.value !== ')' || expectedIndex !== table.columns.length) {
    fail('backup_sql_insert_columns_invalid')
  }
  index += 1
  if (word(tokens[index]) !== 'values' || tokens[index + 1]?.value !== '(') fail('backup_sql_values_shape_invalid')
  index += 2
  for (let columnIndex = 0; columnIndex < columns.length; columnIndex += 1) {
    const next = inspectLiteral(tokens, index)
    index = next
    if (columnIndex < columns.length - 1) {
      if (tokens[index]?.value !== ',') fail('backup_sql_insert_values_invalid')
      index += 1
    }
  }
  if (tokens[index]?.value !== ')') fail('backup_sql_insert_values_invalid')
  index += 1
  if (index < tokens.length) {
    if (tokens[index].value === ',') fail('backup_sql_multirow_insert')
    fail('backup_sql_insert_suffix_forbidden')
  }
  return table
}

function statementKind(effective) {
  const trimmed = effective.trimStart()
  if (trimmed.startsWith('\\')) return 'client'
  const match = /^([A-Za-z_][A-Za-z0-9_$]*)/u.exec(trimmed)
  if (match && CLIENT_COMMANDS.has(match[1].toLowerCase())) return 'client'
  return undefined
}

function inspectStatement(_raw, effective, expected, tableMap) {
  if (statementKind(effective) === 'client') fail('backup_sql_client_command')
  const tokens = stripTerminator(tokenizeSql(effective))
  if (tokens.length === 0) return undefined
  rejectCrossSchema(tokens)
  if (tokens.some(token => token.kind === 'word' && token.value.toLowerCase() === 'global')) {
    fail('backup_sql_global_scope_forbidden')
  }
  const first = word(tokens[0])
  if (first === 'set') {
    inspectSet(tokens)
    return { kind: 'accepted' }
  }
  if (first === 'commit') {
    inspectCommit(tokens)
    return { kind: 'accepted' }
  }
  if (first === 'create') {
    inspectCreate(tokens, expected, tableMap)
    return { kind: 'accepted' }
  }
  if (first === 'insert') {
    const table = inspectInsert(tokens, tableMap)
    table.rows += 1n
    // The scanner's effective stream preserves SQL bytes (including string
    // contents) while removing dump comments. mysqldump puts the table-name
    // comment immediately before INSERT, so hashing raw here would make a
    // source/redump comparison depend on that comment rather than row data.
    table.hash.update(Buffer.from(`${effective.trim()}\n`, 'utf8'))
    return { kind: 'insert', table }
  }
  if (['use', 'drop', 'grant', 'load', 'call', 'alter', 'delete', 'truncate', 'replace', 'update', 'lock', 'unlock'].includes(first)) {
    fail('backup_sql_statement_forbidden')
  }
  if (first === 'delimiter' || CLIENT_COMMANDS.has(first)) fail('backup_sql_client_command')
  if (first === 'create') fail('backup_sql_object_forbidden')
  fail('backup_sql_statement_forbidden')
}

function createBuilder(limit) {
  return { parts: [], pending: '', bytes: 0n, limit }
}

function appendBuilder(builder, value, code = 'backup_sql_statement_too_large') {
  if (!value) return
  const bytes = BigInt(Buffer.byteLength(value, 'utf8'))
  if (builder.bytes + bytes > builder.limit) fail(code)
  builder.bytes += bytes
  builder.pending += value
  if (builder.pending.length >= 8192) {
    builder.parts.push(builder.pending)
    builder.pending = ''
  }
}

function finishBuilder(builder) {
  if (builder.pending) builder.parts.push(builder.pending)
  builder.pending = ''
  return builder.parts.join('')
}

class SqlStreamScanner {
  constructor(limit, onStatement) {
    this.limit = limit
    this.onStatement = onStatement
    this.raw = createBuilder(limit)
    this.effective = createBuilder(limit)
    this.mode = 'normal'
    this.returnMode = 'normal'
    this.pendingSlash = false
    this.pendingCommentMarker = false
    this.pendingCommentMode = 'normal'
    this.pendingDash = false
    this.pendingDashPair = false
    this.blockStar = false
    this.execStar = false
    this.execPrefix = false
    this.quote = undefined
    this.stringEscaped = false
    this.stringQuotePending = false
  }

  appendRaw(value) {
    appendBuilder(this.raw, value)
  }

  appendEffective(value) {
    appendBuilder(this.effective, value)
  }

  enterString(quote) {
    this.quote = quote
    this.stringEscaped = false
    this.stringQuotePending = false
    this.returnMode = this.mode
    this.mode = quote === '`' ? 'backtick' : 'string'
    this.appendEffective(quote)
  }

  enterLineComment() {
    this.appendEffective(' ')
    this.returnMode = this.mode
    this.mode = 'line'
  }

  processString(character) {
    if (this.stringEscaped) {
      this.appendEffective(character)
      this.stringEscaped = false
      return
    }
    if (character === '\\') {
      this.appendEffective(character)
      this.stringEscaped = true
      return
    }
    if (this.stringQuotePending) {
      if (character === this.quote) {
        this.appendEffective(character)
        this.stringQuotePending = false
        return
      }
      this.mode = this.returnMode
      this.stringQuotePending = false
      this.processCode(character)
      return
    }
    this.appendEffective(character)
    if (character === this.quote) this.stringQuotePending = true
  }

  processBlock(character) {
    if (this.blockStar) {
      if (character === '/') {
        this.blockStar = false
        this.mode = this.returnMode
        this.appendEffective(' ')
        return
      }
      this.blockStar = false
    }
    if (character === '*') this.blockStar = true
  }

  processExec(character) {
    if (this.execPrefix) {
      if (isDigit(character)) return
      this.execPrefix = false
    }
    if (this.execStar) {
      if (character === '/') {
        this.execStar = false
        this.mode = 'normal'
        this.appendEffective(' ')
        return
      }
      this.appendEffective('*')
      this.execStar = false
    }
    if (character === '*') {
      this.execStar = true
      return
    }
    this.processCode(character)
  }

  processCode(character) {
    if (character === '/') {
      this.pendingSlash = true
      return
    }
    if (character === '-') {
      this.pendingDash = true
      return
    }
    if (character === '#') {
      this.enterLineComment()
      return
    }
    if (character === ';') {
      this.appendEffective(character)
      this.finishStatement()
      return
    }
    if (character === '\'' || character === '"' || character === '`') {
      this.enterString(character)
      return
    }
    this.appendEffective(character)
  }

  process(character) {
    this.appendRaw(character)
    let current = character
    while (current !== undefined) {
      if (this.mode === 'string' || this.mode === 'backtick') {
        this.processString(current)
        return
      }
      if (this.mode === 'block') {
        this.processBlock(current)
        return
      }
      if (this.mode === 'line') {
        if (current === '\n' || current === '\r') {
          this.mode = this.returnMode
          this.appendEffective(' ')
        }
        return
      }
      if (this.mode === 'exec') {
        this.processExec(current)
        return
      }
      if (this.pendingCommentMarker) {
        this.pendingCommentMarker = false
        if (current === '!') {
          this.mode = 'exec'
          this.execPrefix = true
          this.appendEffective(' ')
          return
        }
        this.returnMode = this.pendingCommentMode
        this.mode = 'block'
        this.appendEffective(' ')
        this.processBlock(current)
        return
      }
      if (this.pendingSlash) {
        this.pendingSlash = false
        if (current === '*') {
          this.pendingCommentMode = this.mode
          this.pendingCommentMarker = true
          return
        }
        this.appendEffective('/')
        continue
      }
      if (this.pendingDashPair) {
        this.pendingDashPair = false
        if (isCommentWhitespace(current)) {
          this.enterLineComment()
          return
        }
        this.appendEffective('-')
        this.appendEffective('-')
        continue
      }
      if (this.pendingDash) {
        this.pendingDash = false
        if (current === '-') {
          this.pendingDashPair = true
          return
        }
        this.appendEffective('-')
        continue
      }
      this.processCode(current)
      return
    }
  }

  finishStatement() {
    const raw = finishBuilder(this.raw)
    const effective = finishBuilder(this.effective)
    this.raw = createBuilder(this.limit)
    this.effective = createBuilder(this.limit)
    this.onStatement(raw, effective)
  }

  finish() {
    if (this.pendingCommentMarker) fail('backup_sql_truncated')
    if (this.pendingSlash) {
      this.pendingSlash = false
      this.appendEffective('/')
    }
    if (this.pendingDashPair) {
      this.pendingDashPair = false
      this.appendEffective('-')
      this.appendEffective('-')
    } else if (this.pendingDash) {
      this.pendingDash = false
      this.appendEffective('-')
    }
    if (this.mode === 'line') this.mode = this.returnMode
    if (this.mode === 'block' || this.mode === 'exec' || this.mode === 'string' || this.mode === 'backtick') {
      fail('backup_sql_truncated')
    }
    const raw = finishBuilder(this.raw)
    const effective = finishBuilder(this.effective)
    if (!effective.trim()) return
    // A complete SQL statement must have gone through finishStatement at a
    // semicolon. Client commands are identified before reporting truncation.
    if (statementKind(effective) === 'client') fail('backup_sql_client_command')
    // Keep the truncation error independent of the SQL text.
    void raw
    fail('backup_sql_truncated')
  }
}

export async function inspectBackupSql(asyncIterableBuffers, options = {}) {
  if (!options || typeof options !== 'object') fail('backup_sql_options_invalid')
  const maxBytes = normalizeLimit(options.maxBytes, DEFAULT_MAX_BYTES, 'backup_sql_max_bytes_invalid')
  const maxStatementBytes = normalizeLimit(options.maxStatementBytes, DEFAULT_MAX_STATEMENT_BYTES, 'backup_sql_max_statement_bytes_invalid')
  const { tables, byName } = prepareTables(options.tables)
  if (!asyncIterableBuffers || (typeof asyncIterableBuffers[Symbol.asyncIterator] !== 'function'
    && typeof asyncIterableBuffers[Symbol.iterator] !== 'function')) fail('backup_sql_input_invalid')

  const result = {
    kind: 'v4_backup_sql_review/v2',
    tables: undefined,
    statementCount: 0,
  }
  const scanner = new SqlStreamScanner(maxStatementBytes, (raw, effective) => {
    const inspected = inspectStatement(raw, effective, byName, byName)
    if (inspected) result.statementCount += 1
  })
  const decoder = new TextDecoder('utf-8', { fatal: true })
  let totalBytes = 0n
  try {
    for await (const chunk of asyncIterableBuffers) {
      if (!(Buffer.isBuffer(chunk) || chunk instanceof Uint8Array) || chunk instanceof DataView) fail('backup_sql_chunk_invalid')
      const bytes = BigInt(chunk.byteLength)
      if (totalBytes + bytes > maxBytes) fail('backup_sql_too_large')
      totalBytes += bytes
      let text
      try {
        text = decoder.decode(chunk, { stream: true })
      } catch {
        fail('backup_sql_invalid_utf8')
      }
      for (const character of text) scanner.process(character)
    }
    let finalText
    try {
      finalText = decoder.decode()
    } catch {
      fail('backup_sql_invalid_utf8')
    }
    for (const character of finalText) scanner.process(character)
    scanner.finish()
  } catch (error) {
    if (error instanceof BackupSqlScopeError) throw error
    throw new BackupSqlScopeError('backup_sql_review_failed')
  }
  for (const table of tables) {
    if (!table.created) fail('backup_sql_missing_table')
  }
  result.tables = tables.map(table => ({ name: table.name, rows: table.rows.toString(), dataSha256: table.hash.digest('hex') }))
  return result
}
