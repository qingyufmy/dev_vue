const WORD_RE = /^[A-Za-z_][A-Za-z0-9_$]*$/
const MAX_TOKENS = 1_000_000

export class BackupSqlScopeError extends Error {
  constructor(code) {
    super(code)
    this.name = 'BackupSqlScopeError'
    this.code = code
  }
}

function fail(code) {
  throw new BackupSqlScopeError(code)
}

function normalizeLimit(value, fallback, code) {
  if (value === undefined) return fallback
  if (typeof value === 'bigint') {
    if (value < 0n) fail(code)
    return value
  }
  if (typeof value === 'number' && Number.isSafeInteger(value) && value >= 0) return BigInt(value)
  fail(code)
}

function isExpectedIdentifier(value) {
  return typeof value === 'string' && value.length > 0 && value.length <= 64 && WORD_RE.test(value)
}

function prepareTables(input) {
  if (!Array.isArray(input) || input.length === 0 || input.length > 8192) fail('backup_sql_tables_invalid')
  const tables = []
  const byName = new Map()
  for (const item of input) {
    if (!item || !isExpectedIdentifier(item.name) || byName.has(item.name)) fail('backup_sql_tables_invalid')
    if (!Array.isArray(item.columns) || item.columns.length === 0 || item.columns.length > 4096) {
      fail('backup_sql_columns_invalid')
    }
    const columns = []
    const names = new Set()
    for (const column of item.columns) {
      if (!column || !isExpectedIdentifier(column.name) || names.has(column.name)) fail('backup_sql_columns_invalid')
      names.add(column.name)
      columns.push(column.name)
    }
    const table = {
      name: item.name,
      columns,
      columnSet: new Set(columns),
      // Generated-column eligibility is deliberately derived from the frozen
      // CREATE TABLE statement, never from caller-supplied metadata.  Keep
      // the set on the table so INSERT validation can only make the narrowly
      // scoped mysqldump omission for columns proven generated by that DDL.
      generatedColumns: new Set(),
      created: false,
      rows: 0n,
      hash: createHash('sha256'),
    }
    byName.set(table.name, table)
    tables.push(table)
  }
  return { tables, byName }
}

function isWhitespace(character) {
  return /\s/u.test(character)
}

function isCommentWhitespace(character) {
  return character === undefined || isWhitespace(character) || character.charCodeAt(0) < 32
}

function isWordStart(character) {
  return character !== undefined && /[A-Za-z_$]/u.test(character)
}

function isWordPart(character) {
  return character !== undefined && /[A-Za-z0-9_$]/u.test(character)
}

function isDigit(character) {
  return character !== undefined && character >= '0' && character <= '9'
}

function isHexDigit(character) {
  return character !== undefined && /^[0-9A-Fa-f]$/u.test(character)
}

function decodeQuotedValue(raw, quote) {
  if (raw.length < 2 || raw[0] !== quote || raw.at(-1) !== quote) fail('backup_sql_literal_invalid')
  let result = ''
  for (let index = 1; index < raw.length - 1;) {
    const character = raw[index]
    if (character === '\\') {
      if (index + 1 >= raw.length - 1) fail('backup_sql_literal_invalid')
      const escaped = raw[index + 1]
      // The exact byte value is immaterial to the scope check; keeping the
      // escaped character makes the comparisons for fixed SET values strict.
      result += escaped
      index += 2
    } else if (character === quote && raw[index + 1] === quote) {
      result += quote
      index += 2
    } else {
      result += character
      index += 1
    }
  }
  return result
}

function stringValue(token) {
  if (token.value === undefined) token.value = decodeQuotedValue(token.raw, token.quote)
  return token.value
}

function addToken(tokens, token) {
  if (tokens.length >= MAX_TOKENS) fail('backup_sql_statement_too_complex')
  tokens.push(token)
}

function decodeIdentifier(raw) {
  if (raw.length < 2 || raw[0] !== '`' || raw.at(-1) !== '`') fail('backup_sql_identifier_invalid')
  let result = ''
  for (let index = 1; index < raw.length - 1;) {
    const character = raw[index]
    if (character === '\\') {
      if (index + 1 >= raw.length - 1) fail('backup_sql_identifier_invalid')
      result += raw[index + 1]
      index += 2
    } else if (character === '`' && raw[index + 1] === '`') {
      result += '`'
      index += 2
    } else {
      result += character
      index += 1
    }
  }
  if (!result || result.includes('.') || result.includes('\u0000')) fail('backup_sql_cross_schema_identifier')
  return result
}

function tokenizeSql(source) {
  const tokens = []
  let index = 0
  while (index < source.length) {
    const character = source[index]
    if (isWhitespace(character)) {
      index += 1
      continue
    }
    if (character === '`') {
      const start = index
      index += 1
      let escaped = false
      let closed = false
      while (index < source.length) {
        const current = source[index]
        if (escaped) {
          escaped = false
          index += 1
        } else if (current === '\\') {
          escaped = true
          index += 1
        } else if (current === '`') {
          if (source[index + 1] === '`') index += 2
          else {
            index += 1
            closed = true
            break
          }
        } else index += 1
      }
      if (!closed) fail('backup_sql_unterminated_literal')
      const raw = source.slice(start, index)
      addToken(tokens, { kind: 'identifier', value: decodeIdentifier(raw), raw })
      continue
    }
    if (character === '\'' || character === '"') {
      const quote = character
      const start = index
      index += 1
      let escaped = false
      let closed = false
      while (index < source.length) {
        const current = source[index]
        if (escaped) {
          escaped = false
          index += 1
        } else if (current === '\\') {
          escaped = true
          index += 1
        } else if (current === quote) {
          if (source[index + 1] === quote) index += 2
          else {
            index += 1
            closed = true
            break
          }
        } else index += 1
      }
      if (!closed) fail('backup_sql_unterminated_literal')
      const raw = source.slice(start, index)
      addToken(tokens, { kind: 'string', value: undefined, quote, raw })
      continue
    }
    if (isWordStart(character)) {
      const start = index
      index += 1
      while (isWordPart(source[index])) index += 1
      const value = source.slice(start, index)
      addToken(tokens, { kind: 'word', value, raw: value })
      continue
    }
    if (isDigit(character) || (character === '.' && isDigit(source[index + 1]))) {
      const start = index
      if (character === '0' && source[index + 1] === 'x') {
        index += 2
        const hexStart = index
        while (isHexDigit(source[index])) index += 1
        if (hexStart === index) fail('backup_sql_literal_invalid')
      } else {
        if (character === '.') index += 1
        while (isDigit(source[index])) index += 1
        if (source[index] === '.') {
          index += 1
          while (isDigit(source[index])) index += 1
        }
        if (source[index] === 'e' || source[index] === 'E') {
          const exponentStart = index
          index += 1
          if (source[index] === '+' || source[index] === '-') index += 1
          const digitsStart = index
          while (isDigit(source[index])) index += 1
          if (digitsStart === index) {
            // Leave the malformed exponent as separate tokens so the INSERT
            // parser rejects it without ever evaluating a numeric expression.
            index = exponentStart
          }
        }
      }
      const raw = source.slice(start, index)
      addToken(tokens, { kind: 'number', value: raw, raw })
      continue
    }
    if ('(),.=+-*/%@;<>!&|^~'.includes(character)) {
      addToken(tokens, { kind: 'punct', value: character, raw: character })
      index += 1
      continue
    }
    fail('backup_sql_syntax_invalid')
  }
  return tokens
}

function word(token) {
  return token?.kind === 'word' ? token.value.toLowerCase() : undefined
}

function isIdentifierToken(token) {
  return token?.kind === 'word' || token?.kind === 'identifier'
}

function isPunctuation(token, value) {
  return token?.kind === 'punct' && token.value === value
}

function identifierValue(token) {
  if (token?.kind === 'identifier') return token.value
  if (token?.kind === 'word' && isExpectedIdentifier(token.value)) return token.value
  fail('backup_sql_identifier_invalid')
}

function stripTerminator(tokens) {
  if (tokens.length === 0) return []
  let semicolonCount = 0
  for (const token of tokens) if (token.kind === 'punct' && token.value === ';') semicolonCount += 1
  if (semicolonCount !== 1 || tokens.at(-1)?.value !== ';') fail('backup_sql_syntax_invalid')
  return tokens.slice(0, -1)
}

function rejectCrossSchema(tokens) {
  for (let index = 0; index < tokens.length; index += 1) {
    const token = tokens[index]
    if (token.kind === 'identifier' && token.value.includes('.')) fail('backup_sql_cross_schema_identifier')
    if (token.kind === 'punct' && token.value === '.' && isIdentifierToken(tokens[index - 1]) && isIdentifierToken(tokens[index + 1])) {
      fail('backup_sql_cross_schema_identifier')
    }
  }
}

function canonicalToken(token) {
  if (token.kind === 'word') return token.value.toLowerCase()
  if (token.kind === 'identifier') return `id:${token.value}`
  if (token.kind === 'string') return `str:${stringValue(token).toLowerCase()}`
  if (token.kind === 'number') return `num:${token.value}`
  return token.value
}

function matches(tokens, pattern) {
  if (tokens.length !== pattern.length) return false
  const actual = tokens.map(canonicalToken)
  return pattern.every((item, index) => actual[index] === item)
}

