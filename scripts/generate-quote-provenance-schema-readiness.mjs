import assert from 'node:assert/strict'
import {readFile,writeFile} from 'node:fs/promises'
import {loadQuoteProvenanceUpgrade} from './lib/quote-provenance-upgrade.mjs'
const root=new URL('../',import.meta.url),plan=await loadQuoteProvenanceUpgrade(root)
const value={step:{id:plan.step.id,checksum:plan.step.checksum},table:plan.step.table,beforeHash:plan.step.beforeHash,afterHash:plan.step.afterHash,
  steps:plan.steps.map(({id,checksum})=>({id,checksum}))}
const output='// Generated by scripts/generate-quote-provenance-schema-readiness.mjs; do not edit.\nexport const quoteProvenanceSchema = '+JSON.stringify(value,null,2)+' as const\n'
const destination=new URL('server/src/modules/trading/infrastructure/quote-provenance-schema.ts',root)
if(process.argv[2]==='--check')assert.equal(await readFile(destination,'utf8'),output)
else {assert.equal(process.argv.length,2);await writeFile(destination,output)}
console.log('Quote provenance schema matches the reviewed 204 to 205 upgrade and canonical MySQL DDL')
