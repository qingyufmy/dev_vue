import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { loadHistoryCollectionTaskUpgrade } from './lib/history-collection-task-upgrade.mjs'
const root = new URL('../', import.meta.url)
const plan = await loadHistoryCollectionTaskUpgrade(root)
const [step] = plan.added
const value = { step: { id: step.id, checksum: step.checksum }, table: { table: step.table, schemaSha256: step.afterHash } }
const rendered = '// Generated by scripts/generate-history-task-schema-readiness.mjs; do not edit.\n'
  + 'export const historyTaskSchema = ' + JSON.stringify(value, null, 2) + ' as const\n'
const destination = new URL('server/src/modules/trade-history/infrastructure/history-task-schema.ts', root)
if (process.argv[2] === '--check') assert.equal(await readFile(destination, 'utf8'), rendered)
else { assert.equal(process.argv.length, 2); await writeFile(destination, rendered) }
console.log('History collection task requirements match the appended 053 target step')
