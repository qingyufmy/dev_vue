import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { loadInstrumentCollectionUpgrade } from './lib/instrument-collection-upgrade.mjs'
const root = new URL('../', import.meta.url)
const reference = JSON.parse(await readFile(new URL('docs/architecture/instrument-schema-reference-20260909.json', root), 'utf8'))
const plan = await loadInstrumentCollectionUpgrade(root, reference)
const value = { steps: [{ id: plan.step.id, checksum: plan.step.checksum }],
  tables: [{ table: plan.step.table, schemaSha256: plan.step.afterHash }] }
const rendered = '// Generated by scripts/generate-instrument-schema-readiness.mjs; do not edit.\n'
  + 'export const instrumentCollectionSchema = ' + JSON.stringify(value, null, 2) + ' as const\n'
const destination = new URL('server/src/modules/trading/infrastructure/instrument-collection-schema.ts', root)
if (process.argv[2] === '--check') assert.equal(await readFile(destination, 'utf8'), rendered)
else { assert.equal(process.argv.length, 2); await writeFile(destination, rendered) }
console.log('Instrument collection schema requirements match migration 045 reference')
